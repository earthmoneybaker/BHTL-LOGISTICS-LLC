-- ============================================================
-- WEEKLY REPORTS
-- ============================================================
CREATE TABLE IF NOT EXISTS weekly_reports (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  report_number VARCHAR(100) UNIQUE NOT NULL,
  report_type VARCHAR(20) NOT NULL DEFAULT 'weekly' CHECK (report_type IN ('daily', 'weekly', 'custom')),
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  truck_id UUID REFERENCES trucks(id) ON DELETE SET NULL,
  driver_id UUID REFERENCES drivers(id) ON DELETE SET NULL,

  -- Revenue
  gross_revenue NUMERIC(12,2) DEFAULT 0,
  fuel_cost NUMERIC(12,2) DEFAULT 0,

  -- Standard deductions (computed from templates)
  eld_fee NUMERIC(12,2) DEFAULT 35.00,
  dispatch_fee NUMERIC(12,2) DEFAULT 0,
  insurance_fee NUMERIC(12,2) DEFAULT 500.00,
  trailer_payment NUMERIC(12,2) DEFAULT 150.00,
  office_authority_fee NUMERIC(12,2) DEFAULT 0,
  driver_salary NUMERIC(12,2) DEFAULT 0,

  -- Extra custom deductions (JSON array: [{name, amount}])
  custom_deductions JSONB DEFAULT '[]',

  -- Totals
  total_deductions NUMERIC(12,2) DEFAULT 0,
  net_revenue NUMERIC(12,2) DEFAULT 0,

  notes TEXT,
  status VARCHAR(50) DEFAULT 'draft' CHECK (status IN ('draft', 'finalized', 'sent')),
  sent_at TIMESTAMPTZ,
  sent_via VARCHAR(50),
  created_by UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_reports_period ON weekly_reports(period_start, period_end);
CREATE INDEX IF NOT EXISTS idx_reports_truck ON weekly_reports(truck_id);
CREATE INDEX IF NOT EXISTS idx_reports_driver ON weekly_reports(driver_id);

-- Load line items for a report
CREATE TABLE IF NOT EXISTS report_load_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id UUID NOT NULL REFERENCES weekly_reports(id) ON DELETE CASCADE,
  load_id UUID REFERENCES loads(id) ON DELETE SET NULL,
  load_number VARCHAR(100),
  pickup_date DATE,
  delivery_date DATE,
  origin VARCHAR(255),
  destination VARCHAR(255),
  miles NUMERIC(10,2),
  load_rate NUMERIC(12,2),
  driver_pay NUMERIC(12,2),
  fuel_cost NUMERIC(12,2) DEFAULT 0,
  included BOOLEAN DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_report_load_items ON report_load_items(report_id);

-- ============================================================
-- TO-DO LIST / REMINDERS
-- ============================================================
CREATE TABLE IF NOT EXISTS todos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(500) NOT NULL,
  description TEXT,
  due_date DATE,
  due_time TIME,
  priority VARCHAR(20) DEFAULT 'medium' CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
  category VARCHAR(50) DEFAULT 'general' CHECK (category IN ('general', 'settlement', 'report', 'compliance', 'fuel', 'maintenance', 'other')),
  is_completed BOOLEAN NOT NULL DEFAULT FALSE,
  completed_at TIMESTAMPTZ,
  is_recurring BOOLEAN DEFAULT FALSE,
  recurrence VARCHAR(20) CHECK (recurrence IN ('daily', 'weekly', 'monthly')),
  related_truck_id UUID REFERENCES trucks(id) ON DELETE SET NULL,
  related_driver_id UUID REFERENCES drivers(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_todos_user ON todos(user_id);
CREATE INDEX IF NOT EXISTS idx_todos_due ON todos(due_date);

-- ============================================================
-- REMINDER SETTINGS (user-configurable alerts)
-- ============================================================
CREATE TABLE IF NOT EXISTS reminder_settings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES users(id) ON DELETE CASCADE,
  reminder_type VARCHAR(100) NOT NULL,
  label VARCHAR(255) NOT NULL,
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  days_before INTEGER DEFAULT 1,  -- how many days before to alert
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

