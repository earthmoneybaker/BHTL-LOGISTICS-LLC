-- ============================================================
-- TEAM DRIVERS (multiple drivers per truck)
-- ============================================================
CREATE TABLE IF NOT EXISTS truck_drivers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  truck_id UUID NOT NULL REFERENCES trucks(id) ON DELETE CASCADE,
  driver_id UUID NOT NULL REFERENCES drivers(id) ON DELETE CASCADE,
  role VARCHAR(50) DEFAULT 'primary' CHECK (role IN ('primary', 'co-driver', 'team')),
  start_date DATE,
  end_date DATE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(truck_id, driver_id)
);

CREATE INDEX IF NOT EXISTS idx_truck_drivers_truck ON truck_drivers(truck_id);
CREATE INDEX IF NOT EXISTS idx_truck_drivers_driver ON truck_drivers(driver_id);

-- ============================================================
-- DEDUCTION TEMPLATES (configurable recurring deductions)
-- ============================================================
CREATE TABLE IF NOT EXISTS deduction_templates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name VARCHAR(255) NOT NULL UNIQUE,
  description TEXT,
  deduction_type VARCHAR(50) NOT NULL CHECK (deduction_type IN ('fixed_weekly', 'fixed_monthly', 'percentage_revenue', 'per_load')),
  amount NUMERIC(12,4),           -- dollar amount (for fixed types)
  percentage NUMERIC(6,4),        -- e.g. 4.0 for 4% (for percentage type)
  applies_to VARCHAR(50) DEFAULT 'truck' CHECK (applies_to IN ('truck', 'driver', 'company')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

